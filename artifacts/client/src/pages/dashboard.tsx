import { useGetDashboardStats, useGetServerInfo } from "@workspace/api-client-react";
import { Database, Activity, CheckCircle, Clock, Download, Cpu, TrendingUp, AlertCircle } from "lucide-react";
import { Link } from "wouter";

function StatCard({
  label, value, sub, icon: Icon, accent,
}: { label: string; value: string | number; sub?: string; icon: React.ElementType; accent?: boolean }) {
  return (
    <div className="bg-card border border-border rounded-sm p-4 flex flex-col gap-3">
      <div className="flex items-center justify-between">
        <span className="text-xs font-medium text-muted-foreground uppercase tracking-widest">{label}</span>
        <Icon className={`w-4 h-4 ${accent ? "text-primary" : "text-muted-foreground"}`} />
      </div>
      <div className={`text-3xl font-bold font-mono tabular-nums ${accent ? "text-primary" : "text-foreground"}`}>{value}</div>
      {sub && <div className="text-xs text-muted-foreground">{sub}</div>}
    </div>
  );
}

export default function Dashboard() {
  const { data: stats, isLoading } = useGetDashboardStats();
  const { data: serverInfo } = useGetServerInfo();

  if (isLoading) {
    return (
      <div className="flex-1 p-6 space-y-6">
        <div className="h-8 w-48 bg-card rounded-sm animate-pulse" />
        <div className="grid grid-cols-2 lg:grid-cols-3 gap-3">
          {Array.from({ length: 6 }).map((_, i) => (
            <div key={i} className="h-28 bg-card border border-border rounded-sm animate-pulse" />
          ))}
        </div>
      </div>
    );
  }

  return (
    <div className="flex-1 overflow-auto p-6 space-y-6">
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-xl font-bold text-foreground tracking-tight">Dashboard</h1>
          <p className="text-xs text-muted-foreground mt-0.5">SAM3 Auto Dataset Factory — overview</p>
        </div>
        <div className="flex items-center gap-2">
          <div className={`w-2 h-2 rounded-full ${stats?.server_status === "ok" ? "bg-emerald-500" : "bg-red-500"} animate-pulse`} />
          <span className="text-xs text-muted-foreground font-mono">
            {serverInfo?.mock_mode ? "MOCK MODE" : `${serverInfo?.device ?? "unknown"}`}
          </span>
        </div>
      </div>

      <div className="grid grid-cols-2 lg:grid-cols-3 gap-3">
        <StatCard label="Datasets" value={stats?.total_datasets ?? 0} icon={Database} sub="total" />
        <StatCard label="Images" value={(stats?.total_images ?? 0).toLocaleString()} icon={TrendingUp} sub="total across all datasets" />
        <StatCard label="Annotations" value={(stats?.total_annotations ?? 0).toLocaleString()} icon={CheckCircle} sub="generated by SAM3" accent />
        <StatCard label="Pending Review" value={stats?.pending_review ?? 0} icon={Clock} sub="annotations awaiting approval" />
        <StatCard label="Completed Jobs" value={stats?.completed_jobs ?? 0} icon={Activity} sub="auto-label runs" />
        <StatCard
          label="Model"
          value={stats?.model_loaded ? "Loaded" : "Not Loaded"}
          icon={Cpu}
          sub={serverInfo?.mock_mode ? "Mock adapter active" : `${serverInfo?.model_name ?? "—"}`}
        />
      </div>

      {stats?.running_jobs && stats.running_jobs > 0 ? (
        <div className="border border-primary/30 bg-primary/5 rounded-sm p-4 flex items-center gap-3">
          <Activity className="w-4 h-4 text-primary animate-pulse" />
          <span className="text-sm text-foreground">
            <span className="font-semibold text-primary">{stats.running_jobs}</span> auto-label {stats.running_jobs === 1 ? "job" : "jobs"} currently running
          </span>
          <Link href="/jobs" className="ml-auto text-xs text-primary hover:underline">View jobs</Link>
        </div>
      ) : null}

      {serverInfo?.mock_mode && (
        <div className="border border-border bg-card rounded-sm p-4 flex items-start gap-3">
          <AlertCircle className="w-4 h-4 text-yellow-500 mt-0.5 flex-shrink-0" />
          <div className="space-y-1">
            <p className="text-sm font-medium text-foreground">Mock Mode Active</p>
            <p className="text-xs text-muted-foreground">
              Running with the mock SAM3 adapter. Auto-label jobs use randomly generated annotations.
              To use real SAM3 inference, configure a GPU server URL in{" "}
              <Link href="/settings" className="text-primary hover:underline">Settings</Link>.
            </p>
          </div>
        </div>
      )}

      <div className="grid grid-cols-2 gap-3">
        <Link href="/datasets/new">
          <div className="border border-dashed border-border hover:border-primary/50 rounded-sm p-4 cursor-pointer transition-colors group">
            <div className="flex items-center gap-2 text-sm font-medium text-muted-foreground group-hover:text-foreground">
              <Database className="w-4 h-4" />
              New Dataset
            </div>
            <p className="text-xs text-muted-foreground mt-1">Upload images and define classes</p>
          </div>
        </Link>
        <Link href="/jobs">
          <div className="border border-dashed border-border hover:border-primary/50 rounded-sm p-4 cursor-pointer transition-colors group">
            <div className="flex items-center gap-2 text-sm font-medium text-muted-foreground group-hover:text-foreground">
              <Download className="w-4 h-4" />
              Export YOLO
            </div>
            <p className="text-xs text-muted-foreground mt-1">Export annotated datasets</p>
          </div>
        </Link>
      </div>
    </div>
  );
}
